import { SLOT_COUNT } from "./icons";

// Each pack fills the 24 slots of icons.ts. Slots 0–19 follow LOOKALIKE_SLOT_GROUPS, so every
// pack must put look-alikes at the same positions (0–4, 5–7, 8–11, 12–14, 15–16, 17–19).
// Icons are Microsoft Fluent Emoji 3D images (src/ui/emojiImages.ts); `glyph` is the matching
// Unicode emoji, kept so VoiceOver / TalkBack read the icon's name in the player's language.
export interface PackIcon {
  glyph: string;
  asset: string;
}

export interface IconPack {
  id: string;
  icons: readonly PackIcon[];
  /** How the pack is unlocked: free, bought with coins, a store product, or Pairs+. */
  price: { kind: "free" } | { kind: "coins"; amount: number } | { kind: "iap"; productId: string } | { kind: "plus" };
}

