export const DEFAULT_PACK_ID = "party";

export function getPack(id: string): IconPack {
  return ICON_PACKS.find((p) => p.id === id) ?? ICON_PACKS[0];
}

const MISSING: PackIcon = { glyph: "?", asset: "prohibited" };

/** Icon for a dealt slot ("0".."23") in the given pack. */
export function iconFor(pack: IconPack, slot: string): PackIcon {
  const index = Number(slot);
  return Number.isInteger(index) && index >= 0 && index < SLOT_COUNT ? pack.icons[index] : MISSING;
}
